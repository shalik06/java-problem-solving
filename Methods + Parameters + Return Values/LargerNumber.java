// max(int a, int b) → Return the larger number.
public class LargerNumber {
    public static int max(int a, int b) {
    return Math.max(a, b);
        
    }
    public static void main(String[] args) {
        int result = max(30, 50);
        System.out.println(result);
        
        
    }
    
}
