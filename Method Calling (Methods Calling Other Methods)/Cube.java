// Create:

// public static int cube(int n)

// It should return:

// n × n × n

// Example:

// System.out.println(cube(3));

// Output:

// 27

// 💡 Don't use loops. Just use multiplication.
public class Cube {
    public static int cube(int n) {
        return n*n*n;
        
    }
   
    public static void main(String[] args) {
      System.out.println(cube(3));
    }
    
}
