// Create this method:

// public static String fullName(String first, String last)

// It should return:

// first + " " + last

// Example:

// System.out.println(fullName("Md", "Shalik"));

// Expected output:

// Md Shalik
public class FullName {
    public static String fullname(String first , String last) {
        return first + last ;
        
    }
    public static void main(String[] args) {
        System.out.println(fullname("md", "shalik"));
    }
    
}
